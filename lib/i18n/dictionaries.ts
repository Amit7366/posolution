export const dictionaries: Record<AppLocale, typeof en> = { en, bn: bn as typeof en };

function resolve(path: string, tree: unknown): string | undefined {
  const parts = path.split(".");
  let cur: unknown = tree;
  for (const p of parts) {
    if (cur !== null && typeof cur === "object" && p in cur) {
      cur = (cur as Record<string, unknown>)[p];
    } else {
      return undefined;
    }
  }
  return typeof cur === "string" ? cur : undefined;
}

function applyVars(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  let out = s;
  for (const [k, v] of Object.entries(vars)) {
    out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}

export function translate(
  locale: AppLocale,
  key: string,
  vars?: Record<string, string | number>
): string {
  const raw = resolve(key, dictionaries[locale]);
  const base = raw !== undefined ? raw : resolve(key, dictionaries.en) ?? key;
  return applyVars(base, vars);
}
